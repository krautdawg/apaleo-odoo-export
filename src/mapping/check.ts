export interface CheckMappingOptions {
  /** `odoo.version`: which codes a fresh database gives the generated cash and transfer accounts (`N-GENERATED-ACCOUNT`). */
  version?: OdooVersion | undefined;
}

const KNOWN_TYPES: ReadonlySet<string> = new Set([...ACCOUNT_TYPES, ANY_TYPE]);

/** The VAT rates German law knows today (UStG § 12). */
export const GERMAN_VAT_RATES: readonly number[] = [0, 7, 19];

/** The rates of the second half of 2020 (Zweites Corona-Steuerhilfegesetz). */
const RATES_2020: ReadonlySet<number> = new Set([16, 5]);

/** Odoo's rule for an account code (`account.account`, research §2). */
const ACCOUNT = /^[A-Za-z0-9.]{1,64}$/;
/** A chart-template id such as `tax_ust_7_skr03`. */
const TEMPLATE_TAX_ID = /^[a-z0-9_]+$/;
/** A full External ID such as `__import__.ust_7_hotel` or `account.1_tax_ust_7_skr03`. */
const EXTERNAL_TAX_ID = /^[A-Za-z0-9_]+\.[A-Za-z0-9_]+$/;

const percents = (rates: readonly number[]) => rates.map((rate) => `${rate} %`).join(', ');

/**
 * Offline validation of a loaded mapping for Odoo: account code format, tax value
 * format and placement, tax and rate together, the known l10n_de sale taxes and
 * their rates, the non-taxable tax of Kz 45, German rates, accounts with a
 * default tax or generated by Odoo, and the row's rate against the apaleo rate.
 * Structural problems (duplicates, forbidden wildcards) already fail `loadMapping`.
 */
export function checkMapping(mapping: Mapping, options: CheckMappingOptions = {}): Finding[] {
  const findings: Finding[] = [];
  const ignored = mapping.rows.filter((row) => VAT_ACCOUNT_TYPES.has(row.apaleoType));
  if (ignored.length > 0) {
    findings.push({
      code: 'N-VAT-ROW-IGNORED',
      message:
        `${ignored.length} row(s) for Vat or VatOnLiabilities accounts (${ignored.map((r) => `line ${r.line}`).join(', ')}) ` +
        'are ignored: those lines are always skipped because Odoo computes the tax lines from the tax of the revenue or deposit line',
    });
  }
  for (const row of mapping.rows) {
    if (!VAT_ACCOUNT_TYPES.has(row.apaleoType)) findings.push(...checkRow(row, options));
  }
  return findings;
}

/** The `checkMapping` warnings about a row's tax that the export repeats for the rows it uses. */
export const USED_ROW_TAX_WARNINGS: ReadonlySet<string> = new Set(['W-TAX-RATE', 'W-TAX-UNCHECKED', 'W-TAX-KZ45']);

/**
 * The export's error for a used row whose known l10n_de tax has another rate in
 * Odoo than the row books (`W-TAX-RATE` in `mapping check`): the writer would fit
 * the base for the row's rate while Odoo computes its own, so the VAT would be
 * wrong and Odoo would add an "Automatic Balancing Line".
 */
export const USED_ROW_TAX_RATE_ERROR = 'E-TAX-RATE-WRONG';

/**
 * `W-TAX-UNCHECKED` and `W-TAX-KZ45` for the mapping rows the lines of a period
 * actually resolve to, and `E-TAX-RATE-WRONG` in place of `W-TAX-RATE`, one finding
 * per code that names every row it concerns (`lines 3, 6: ...`). The posting guard
 * compares rates only, so a swapped tax (`tax_ust_19_skr03` at 7 %) or a custom tax
 * would reach the file silently; the export and schedule runs never call
 * `mapping check`, so they report these findings in the dry run and the protocol
 * themselves. A known tax at the wrong rate blocks the file: Odoo always computes
 * the tax at its own rate.
 */
export function checkUsedTaxes(mapping: Mapping, lines: readonly LedgerLine[], chart: ChartIndex | undefined, options: CoverageOptions): Finding[] {
  const used = new Map<number, MappingRow>();
  for (const line of lines) {
    if (VAT_ACCOUNT_TYPES.has(line.debit.type) || VAT_ACCOUNT_TYPES.has(line.credit.type)) continue;
    const rate = options.rateOf(line);
    for (const account of [line.debit, line.credit]) {
      const row = resolve(mapping, account, { rate, ...(chart ? { chart } : {}) });
      if (row && row.odooAccount !== '' && taxOf(row) !== undefined) used.set(row.line, row);
    }
  }
  const merged = new Map<string, { finding: Finding; lines: number[] }>();
  for (const row of [...used.values()].sort((a, b) => a.line - b.line)) {
    for (const finding of checkRow(row, {})) {
      if (!USED_ROW_TAX_WARNINGS.has(finding.code)) continue;
      const wrongRate = finding.code === 'W-TAX-RATE';
      const code = wrongRate ? USED_ROW_TAX_RATE_ERROR : finding.code;
      const body = finding.message.slice(`line ${row.line}: `.length).replace(
        /\. Check that the taxes are not swapped$/,
        wrongRate
          ? '. Odoo computes the tax at its own rate while the file fits the base for the row\'s rate, so the VAT would be wrong and Odoo would add an ' +
              '"Automatic Balancing Line". Correct odoo_tax or tax_percent of the row (are the taxes swapped?), run mapping check and export again'
          : '. Check that the taxes are not swapped',
      );
      const key = `${code}\u0000${body}`;
      const entry = merged.get(key) ?? { finding: { ...finding, code, message: body }, lines: [] };
      entry.lines.push(row.line);
      merged.set(key, entry);
    }
  }
  return [...merged.values()].map(({ finding, lines }) => ({
    ...finding,
    message: `${lines.length === 1 ? 'line' : 'lines'} ${lines.join(', ')} of the mapping file: ${finding.message}`,
  }));
}

const KNOWN_TAX_LIST = L10N_DE_TAXES.map((tax) => tax.id).join(', ');

function checkRow(row: MappingRow, options: CheckMappingOptions): Finding[] {
  const where = `line ${row.line}`;
  const findings: Finding[] = [];
  const add = (code: string, field: string, value: string, message: string) => findings.push({ code, message: `${where}: ${message}`, field, value });
  if (!KNOWN_TYPES.has(row.apaleoType)) {
    add('W-UNKNOWN-TYPE', 'apaleo_type', row.apaleoType, `apaleo_type "${row.apaleoType}" is not an apaleo account type (${ACCOUNT_TYPES.join(', ')})`);
  }
  for (const [field, text] of [['apaleo_vat_percent', row.apaleoVatPercent], ['tax_percent', row.taxPercent]] as const) {
    if (Number.isNaN(parsePercent(text) ?? 0)) add('E-VAT-PERCENT', field, text, `${field} "${text}" is not a percentage`);
  }
  const tax = taxOf(row);
  const rate = parsePercent(row.taxPercent);
  const rateKnown = rate !== undefined && !Number.isNaN(rate);
  if (tax !== undefined && !TEMPLATE_TAX_ID.test(tax) && !EXTERNAL_TAX_ID.test(tax)) {
    add(
      'E-TAX-FORMAT',
      'odoo_tax',
      tax,
      `odoo_tax "${tax}" must be the chart-template id of an Odoo tax (lower case letters, digits and _, for example tax_ust_7_skr03) ` +
        'or a full External ID (module.name, for example __import__.ust_7_hotel)',
    );
  } else if (tax !== undefined && NO_TAX_TYPES.has(row.apaleoType)) {
    add(
      'E-TAX-NOT-ALLOWED',
      'odoo_tax',
      tax,
      `apaleo type ${row.apaleoType} is a payment, guest claim or company invoice and carries no VAT, but the row has the Odoo tax ${tax}: ` +
        'Odoo would compute VAT on the money or the claim. Leave odoo_tax and tax_percent empty on this row, and put the tax on the revenue or deposit row',
    );
  } else if (tax !== undefined) {
    if (rate === undefined) add('E-VAT-RATE-MISSING', 'tax_percent', '', `the Odoo tax ${tax} needs its rate in tax_percent (0 for a tax at 0 %)`);
    const known = knownTax(tax);
    if (known === undefined) {
      add(
        'W-TAX-UNCHECKED',
        'odoo_tax',
        tax,
        `the tool does not know the Odoo tax ${tax} (it knows the l10n_de sale taxes ${KNOWN_TAX_LIST}). ` +
          `Confirm with your Steuerberater that it is a sale tax of the Odoo company${rateKnown ? ` with the rate ${rate} %` : ''}`,
      );
    } else if (rateKnown && rate !== known.rate) {
      add('W-TAX-RATE', 'odoo_tax', tax, `the Odoo tax ${tax} has the rate ${known.rate} % in Odoo, but the row books it at ${rate} %. Check that the taxes are not swapped`);
    }
    if (known && NOT_TAXABLE_TAXES.has(known.id)) {
      add(
        'W-TAX-KZ45',
        'odoo_tax',
        tax,
        `the Odoo tax ${tax} is the non-taxable 0 % tax: Odoo reports its base in UStVA Kz 45 (nicht steuerbare Umsätze, Leistungsort im Ausland). ` +
          'Domestic untaxed revenue, Schadenersatz and durchlaufende Posten such as a guest-owed Kurtaxe carry no tax at all: leave odoo_tax and tax_percent empty',
      );
    }
  } else if (rateKnown && rate > 0) {
    add('E-TAX-MISSING', 'odoo_tax', '', `tax_percent is ${rate} %, but odoo_tax is empty: Odoo computes no VAT without a tax. Fill in the Odoo tax of that rate`);
  }
  if (rateKnown && !GERMAN_VAT_RATES.includes(rate)) {
    add(
      'W-VAT-RATE-UNUSUAL',
      'tax_percent',
      row.taxPercent,
      `tax_percent ${rate} % is not a German VAT rate (${percents(GERMAN_VAT_RATES)}). ` +
        (RATES_2020.has(rate) ? `${rate} % applied from 2020-07-01 to 2020-12-31: exports for that period need your Steuerberater` : 'Was this row copied from another country\'s mapping?'),
    );
  }
  if (row.odooAccount === '') return findings;

  if (!ACCOUNT.test(row.odooAccount)) {
    add('E-ACCOUNT-FORMAT', 'odoo_account', row.odooAccount, `Odoo account "${row.odooAccount}" must be an account code of 1 to 64 characters of A-Z, a-z, 0-9 and "."`);
  }
  const defaultTax = tax === undefined ? defaultTaxOf(row.odooAccount) : undefined;
  if (defaultTax) {
    add(
      'N-DEFAULT-TAX-ACCOUNT',
      'odoo_tax',
      '',
      `account ${row.odooAccount} carries the default tax ${defaultTax.rate} % in Odoo's ${defaultTax.chart.toUpperCase()} template, and the row books it without tax: ` +
        'the file sets the line without tax explicitly (empty tax cell). Do not edit such a line by hand in Odoo, which would give it the default tax again in 17 and 18',
    );
  }
  if (row.apaleoType === 'Payments') findings.push(...generatedAccountNote(row, where, options.version));
  const odooRate = rowRate(row);
  const apaleoRate = parsePercent(row.apaleoVatPercent);
  if (odooRate !== undefined && apaleoRate !== undefined && !Number.isNaN(apaleoRate) && odooRate !== apaleoRate) {
    add(
      'E-VAT-MISMATCH',
      'tax_percent',
      String(odooRate),
      `apaleo account ${row.apaleoAccount} (${row.apaleoType}) has VAT ${apaleoRate} %, but the row books ${odooRate} % on Odoo account ` +
        `${row.odooAccount}. Map it to an account for ${apaleoRate} % with the matching Odoo tax and tax_percent`,
    );
  }
  return findings;
}

/**
 * `N-GENERATED-ACCOUNT` for a Payments row on a code of the Kasse or the
 * Geldtransit account, which Odoo generates at company setup: the code exists
 * only if Odoo created it so, so it must be compared with the Kontenplan.
 */
function generatedAccountNote(row: MappingRow, where: string, version: OdooVersion | undefined): Finding[] {
  const chart = generatedChartOf(row.odooAccount);
  if (!chart) return [];
  const versions = version === undefined ? ([17, 18, 19] as const) : [version];
  const fresh = versions.map((v) => {
    const { cash, transfer } = generatedAccounts(chart, v);
    return `${version === undefined ? `Odoo ${v}: ` : ''}Kasse ${cash}, Geldtransit ${transfer}`;
  });
  const freshCodes = new Set(versions.flatMap((v) => Object.values(generatedAccounts(chart, v))));
  const missing = freshCodes.has(row.odooAccount) ? '' : ` and no ${row.odooAccount}`;
  return [
    {
      code: 'N-GENERATED-ACCOUNT',
      message:
        `${where}: Odoo creates the Kasse and the Geldtransit account at company setup instead of taking them from the chart template, ` +
        `so ${row.odooAccount} exists only if Odoo created it with that code. A fresh ${chart.toUpperCase()} database of Odoo ${version ?? '17, 18 or 19'} has ` +
        `${fresh.join('; ')}${missing}. Compare the code with the Kontenplan of the Odoo company (Buchhaltung > Konfiguration > Kontenplan)`,
      field: 'odoo_account',
      value: row.odooAccount,
    },
  ];
}

export interface CoverageOptions {
  /**
   * The rate each line's rows are resolved with. The posting rules' `releaseRateOf`
   * gives the inferred rate of an untaxed deposit release (undefined when none can
   * be inferred) and the line's own rate (`lineRate`) otherwise.
   */
  rateOf: (line: LedgerLine) => number | undefined;
  /** `odoo.version`, for the generated Kasse and Geldtransit in the fix hints. Default 18. */
  version?: OdooVersion | undefined;
}

/** A line without a tax entry left after normalising. */
function isUntaxed(line: LedgerLine): boolean {
  return !line.taxes.some((tax) => tax.percent !== 0 || tax.amountCents !== 0);
}

interface Booked {
  account: AccountRef;
  lines: number;
  grossCents: number;
}

interface Unmapped extends Booked {
  rate: number | undefined;
  row: MappingRow | undefined;
  /**
   * Set for accounts outside the chart with a parent (per-reservation and folio
   * accounts): they are reported once per parent, type and rate.
   */
  group?: { parent: string; accounts: Set<string> };
}

interface Mismatch extends Booked {
  rate: number;
  row: MappingRow;
  odooRate: number;
}

/** Untaxed deposit releases whose VAT rate cannot be inferred. */
interface UnknownRates {
  accounts: Set<string>;
  lines: number;
  grossCents: number;
}

function add<T extends Booked>(map: Map<string, T>, key: string, line: LedgerLine, create: () => T): void {
  const entry = map.get(key) ?? create();
  entry.lines += 1;
  entry.grossCents += line.grossCents;
  map.set(key, entry);
}

const byAccount = (a: Booked, b: Booked) => a.account.type.localeCompare(b.account.type) || a.account.number.localeCompare(b.account.number);

const MAX_EXAMPLES = 3;

/**
 * Checks every account booked in `lines` against the mapping:
 * - `E-UNMAPPED` for an account that does not resolve to a row with an Odoo
 *   account, with its type, name, line count and gross total;
 * - `E-VAT-MISMATCH` for a VAT-relevant account whose row books another rate
 *   than the line carries, for example a revenue account at 10 % that resolves
 *   through a parent row to an 8.1 % account;
 * - `E-VAT-RATE-UNKNOWN` once for all untaxed deposit releases whose rate
 *   `rateOf` cannot infer (the export stops on them).
 * Lines with a Vat or VatOnLiabilities side are skipped by the posting rules,
 * so they need no mapping.
 */
export function checkCoverage(
  mapping: Mapping,
  lines: readonly LedgerLine[],
  chart: ChartIndex | undefined,
  options: CoverageOptions,
): Finding[] {
  const { rateOf } = options;
  const resolveAt = (account: AccountRef, rate: number | undefined) => resolve(mapping, account, { rate, ...(chart ? { chart } : {}) });
  const unmapped = new Map<string, Unmapped>();
  const mismatches = new Map<string, Mismatch>();
  const unknownRate: UnknownRates = { accounts: new Set(), lines: 0, grossCents: 0 };
  for (const line of lines) {
    if (VAT_ACCOUNT_TYPES.has(line.debit.type) || VAT_ACCOUNT_TYPES.has(line.credit.type)) continue;
    const rate = rateOf(line);
    for (const account of [line.debit, line.credit]) {
      if (rate === undefined && account.type === 'Liabilities' && isUntaxed(line)) {
        unknownRate.accounts.add(account.number);
        unknownRate.lines += 1;
        unknownRate.grossCents += line.grossCents;
        continue;
      }
      const row = resolveAt(account, rate);
      if (row && row.odooAccount !== '') {
        // A row whose own apaleo_vat_percent equals the line's rate is checked by checkMapping.
        if (rate === undefined || !OUTPUT_TAX_TYPES.has(account.type) || parsePercent(row.apaleoVatPercent) === rate) continue;
        const odooRate = rowRate(row);
        if (odooRate === undefined || odooRate === rate) continue;
        add(mismatches, `${row.line}\u0000${account.number}\u0000${account.type}\u0000${rate}`, line, () => ({
          account, rate, row, odooRate, lines: 0, grossCents: 0,
        }));
        continue;
      }
      const rated = VAT_RELEVANT_TYPES.has(account.type) && (!row || row.apaleoAccount !== account.number);
      const parent = !chart?.has(account.number) ? account.parentNumber : undefined;
      const key = `${parent === undefined ? account.number : `parent ${parent}`}\u0000${account.type}${rated ? `\u0000${rate}` : ''}`;
      add(unmapped, key, line, () => ({
        account: parent === undefined ? account : { number: parent, name: chart?.find(parent, account.type)?.name ?? parent, type: account.type },
        rate,
        row,
        lines: 0,
        grossCents: 0,
        ...(parent === undefined ? {} : { group: { parent, accounts: new Set<string>() } }),
      }));
      unmapped.get(key)?.group?.accounts.add(account.number);
    }
  }
  const hint: Hint = {
    version: options.version ?? 18,
    wildcardRow: (type, rate) =>
      mapping.rows.find((row) => row.apaleoAccount === WILDCARD && row.apaleoType === type && parsePercent(row.apaleoVatPercent) === rate),
  };
  return [
    ...[...unmapped.values()].sort(byAccount).map((entry) => unmappedFinding(entry, hint)),
    ...(unknownRate.lines > 0 ? [unknownRateFinding(unknownRate)] : []),
    ...[...mismatches.values()].sort(byAccount).map(mismatchFinding),
  ];
}

function bookedText({ lines, grossCents }: Pick<Booked, 'lines' | 'grossCents'>): string {
  return `${lines} line${lines === 1 ? '' : 's'}, gross ${formatCents(grossCents)}`;
}

interface Hint {
  /** The Odoo version the template's generated accounts are resolved for. */
  version: OdooVersion;
  /** The mapping's wildcard row for a VAT-relevant type at a rate, if it has one. */
  wildcardRow: (type: string, rate: number) => MappingRow | undefined;
}

/**
 * The fix when an empty parent row wins over an empty wildcard row that already
 * exists (resolve prefers the parent): name that row instead of asking to add it.
 */
function emptyWildcardFix(wildcard: MappingRow, type: string, rate: number): string {
  return `fill in odoo_account on the wildcard row for ${type} at ${rate} % on line ${wildcard.line}`;
}

/** Labels of the template's accounts in the fix hints. */
const TEMPLATE_ACCOUNT_LABELS: Readonly<Record<string, string>> = {
  AccountsReceivable: 'Forderungen aus Lieferungen und Leistungen',
  Receivables: 'Gästeforderungen',
  Payments: 'Geldtransit',
};

/**
 * The wildcard row to add for a type, as it is written in the file, with the
 * SKR03 hotel template's account (and for VAT-relevant types its tax) as example.
 */
function wildcardHint(type: string, rate: number | undefined, { version }: Hint): string {
  const rated = VAT_RELEVANT_TYPES.has(type);
  const template = templateWildcard(shippedTemplate(), type, rated ? rate : undefined, { version });
  if (!rated) {
    const label = TEMPLATE_ACCOUNT_LABELS[type];
    return `the wildcard row \`*;${type};;;${template?.odooAccount ?? '<Odoo account>'}\`${label && template ? ` (${label})` : ''}`;
  }
  const at = rate === undefined ? '' : ` at ${rate} %`;
  const example = template
    ? `\`*;${type};;${rate};${template.odooAccount};${template.odooTax};${rate}\` from the SKR03 hotel template`
    : `\`*;${type};;${rate};<Odoo account>;${rate === 0 ? '' : '<Odoo tax>'};${rate}\``;
  return `a wildcard row \`*;${type}\`${at}, for example ${example}`;
}

/**
 * `E-UNMAPPED` with the row to change: an exact empty row by its line; an empty
 * parent row with the wildcard row to add instead (for VAT-relevant types never
 * "fill in the parent row": one Odoo account cannot serve every rate); no row
 * at all with the row or wildcard row to add.
 */
function unmappedFinding(entry: Unmapped, hint: Hint): Finding {
  const { account, rate, row, group } = entry;
  const vatRelevant = VAT_RELEVANT_TYPES.has(account.type);
  const at = vatRelevant && rate !== undefined ? ` at ${rate} %` : '';
  let what = `apaleo account ${account.number} (${account.type}, "${account.name}") is`;
  if (group) {
    const accounts = [...group.accounts].sort();
    const more = accounts.length > MAX_EXAMPLES ? ` and ${accounts.length - MAX_EXAMPLES} more` : '';
    const count = accounts.length === 1 ? `1 ${account.type} account` : `${accounts.length} ${account.type} accounts`;
    what = `${count} of reservations or folios under parent ${group.parent}${at} (${accounts.slice(0, MAX_EXAMPLES).join(', ')}${more}) ${accounts.length === 1 ? 'is' : 'are'}`;
  }
  const emptyParent = row && row.apaleoAccount !== WILDCARD && row.apaleoAccount !== (group ? undefined : account.number);
  const wildcard = wildcardHint(account.type, rate, hint);
  let fix: string;
  if (row && !emptyParent) {
    fix = `fill in odoo_account on line ${row.line} of the mapping file`;
  } else if (vatRelevant && rate === undefined) {
    fix = `the lines carry more than one VAT rate, so no wildcard applies; add a row for ${account.number} ${account.type}`;
  } else if (account.type === 'Revenues' && row) {
    fix = `the parent row for ${row.apaleoAccount} on line ${row.line} has no Odoo account; add a row for ${account.number} Revenues with an Odoo account and tax for${at}`;
  } else if (account.type === 'Revenues') {
    fix = `add a row with apaleo_account ${account.number}, apaleo_type Revenues and an Odoo account and tax`;
  } else if (row && vatRelevant) {
    const existing = rate === undefined ? undefined : hint.wildcardRow(account.type, rate);
    const add = existing && rate !== undefined ? emptyWildcardFix(existing, account.type, rate) : `add ${wildcard}`;
    fix = `the parent row for ${row.apaleoAccount} on line ${row.line} has no Odoo account and does not apply to ${account.type} at different VAT rates; ${add}`;
  } else if (row) {
    fix = `fill in odoo_account for the parent row ${row.apaleoAccount} on line ${row.line}, or add ${wildcard}`;
  } else if (group && vatRelevant) {
    fix = `add ${wildcard}`;
  } else if (group) {
    fix = `add a row for ${group.parent} ${account.type} or ${wildcard}`;
  } else if (vatRelevant) {
    fix = `add a row for ${account.number} ${account.type}, or ${wildcard}`;
  } else {
    fix = `add a row with apaleo_account ${account.number}, apaleo_type ${account.type} and an Odoo account`;
  }
  return {
    code: 'E-UNMAPPED',
    message: `${what} not mapped (${bookedText(entry)}): ${fix}`,
    field: 'apaleo_account',
    value: account.number,
  };
}

function mismatchFinding(entry: Mismatch): Finding {
  const { account, rate, row, odooRate } = entry;
  const via = row.apaleoAccount === account.number ? `its row on line ${row.line}` : `line ${row.line} (apaleo account ${row.apaleoAccount})`;
  return {
    code: 'E-VAT-MISMATCH',
    message:
      `apaleo account ${account.number} (${account.type}, "${account.name}") is booked at ${rate} % (${bookedText(entry)}), ` +
      `but it uses ${via} of the mapping, which books ${odooRate} % on Odoo account ${row.odooAccount}. ` +
      `Add a row for ${account.number} ${account.type} with an Odoo account and tax for ${rate} %`,
    field: 'apaleo_account',
    value: account.number,
  };
}

/** One finding for all untaxed deposit releases whose VAT rate cannot be inferred. */
function unknownRateFinding(releases: UnknownRates): Finding {
  const accounts = [...releases.accounts].sort();
  const names = accounts.slice(0, 3);
  const more = accounts.length > names.length ? ` and ${accounts.length - names.length} more` : '';
  return {
    code: 'E-VAT-RATE-UNKNOWN',
    message:
      `${releases.lines} deposit release${releases.lines === 1 ? '' : 's'} (${bookedText(releases)}, ` +
      `${accounts.length === 1 ? 'account' : 'accounts'} ${names.join(', ')}${more}): apaleo settled a guest's prepaid deposit ` +
      'against the bill without a VAT amount, and the VAT rate cannot be found: there is no PostPrepaymentVat line of the same day ' +
      'and reservation with a rate, and the chart of accounts gives the deposit account none. The export stops rather than book them ' +
      `without VAT. ${REPORT_PROBLEM_HINT}`,
    field: 'apaleo_account',
    value: names[0] ?? '',
  };
}
